  function getLang() {
    try {
      const stored = localStorage.getItem(STORAGE_KEY);
      if (stored === 'es' || stored === 'en') return stored;
    } catch (_) {}
    return DEFAULT_LANG;
  }

  function setLang(lang) {
    if (lang !== 'es' && lang !== 'en') return;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (_) {}
    applyTranslations();
    document.dispatchEvent(new CustomEvent('novadef-lang-changed', { detail: { lang } }));
  }

  function t(key, fallback) {
    const entry = DICT[key];
    if (!entry) return fallback !== undefined ? fallback : key;
    const lang = getLang();
    return entry[lang] || entry[DEFAULT_LANG] || fallback || key;
  }

  function applyTranslations(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      const translated = t(key);
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = translated;
      } else {
        el.textContent = translated;
      }
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });
    document.querySelectorAll('.novadef-lang-btn').forEach((btn) => {
      const lang = btn.getAttribute('data-lang');
      btn.classList.toggle('active', lang === getLang());
    });
  }

